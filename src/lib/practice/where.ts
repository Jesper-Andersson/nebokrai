// The sentences of the "Де? or Куди?" items of grammar practice (/practice):
// у, на and під take the locative (під: the instrumental) for where something
// is and the accusative for where it goes, so the ending alone tells the two
// apart.
//
//   Він сидів на ліжку.     де?     the locative: he sat there
//   Він сів на ліжко.       куди?   the accusative: he sat down onto it
//
// The cloze table (data/import_wiktionary.py, add_cloze) cannot be used as it
// is: about half of its у/на + accusative sentences are not about where
// anything goes. У вівторок is a day, чекати на поліцію and ціна на бензин
// are what a verb or a noun asks for, впасти в розпач is a state. Its
// locative sentences have the same trouble on a smaller scale: у масці is
// what someone wears, у паніці how they feel.
//
// So these were read and picked by hand, in November 2026: a sentence is
// here only if де? or куди? asks plainly about it, and it has no де or куди
// of its own to give the answer away. Idioms, swearing and near repeats were
// left out. A sentence is named by its Tatoeba id, which a rebuild of the
// dictionary keeps; one that a rebuild drops is passed over (a test lists
// any that are missing).
//
// Nothing here imports from Svelte or reads the database, so `npm test` runs
// it.

